#!/usr/bin/env bash
# shellcheck shell=bash
#
# Create an additional Indigo Compose environment from the base .env file with
# every published port incremented and separate host bind mounts, so a second
# instance can run beside the first without editing compose.yaml by hand.
#
# Usage: scripts/new.sh <name> [offset] [--force]
set -euo pipefail

base_file="${BASE_ENV_FILE:-.env}"
default_offset=1
force=0

port_keys=(
    INFERENCE_PUBLISHED_PORT
    CODE_SERVER_PUBLISHED_PORT
    VERDACCIO_PUBLISHED_PORT
    JUPYTER_PUBLISHED_PORT
    MARIMO_PUBLISHED_PORT
    OPENVIKING_PUBLISHED_PORT
    PINOKIO_PUBLISHED_PORT
    PINOKIO_PROXY_PUBLISHED_PORT
    MCP_FILESYSTEM_PUBLISHED_PORT
    MCP_RUST_ANALYZER_PUBLISHED_PORT
)

usage() {
    cat << EOF
Usage: ${0##*/} <name> [offset] [--force]

  <name>    Instance name; also names the env file and Compose project.
  offset    Integer added to every published port. Default: ${default_offset}.
  --force   Overwrite an existing instance file.

Environment:
  BASE_ENV_FILE  Base env file to copy. Default: ${base_file}

Example:
  ${0##*/} two
  ${0##*/} three 1000
EOF
}

base_value() {
    awk -F= -v key="$1" '$1 == key { print substr($0, index($0, "=") + 1); exit }' "${base_file}"
}

fail() {
    echo "error: $*" >&2
    exit 1
}

if [[ "${1:-}" == "-h" || "${1:-}" == "--help" ]]; then
    usage
    exit 0
fi

positional=()
while [[ $# -gt 0 ]]; do
    case "$1" in
        --force)
            force=1
            ;;
        -*)
            echo "error: unknown option: $1" >&2
            usage >&2
            exit 2
            ;;
        *)
            positional+=("$1")
            ;;
    esac
    shift
done

name="${positional[0]:-}"
offset="${positional[1]:-${default_offset}}"

if [[ -z "${name}" ]]; then
    echo "error: an instance name is required" >&2
    usage >&2
    exit 2
fi

if [[ ! "${name}" =~ ^[a-z0-9][a-z0-9-]*$ ]]; then
    echo "error: invalid instance name: ${name}" >&2
    echo "error: use lowercase letters, digits, and dashes" >&2
    exit 2
fi

if [[ ! "${offset}" =~ ^-?[0-9]+$ ]]; then
    echo "error: offset must be an integer: ${offset}" >&2
    exit 2
fi

[[ -f "${base_file}" ]] || fail "base env file not found: ${base_file}"
[[ -x ./scripts/check.sh || -f ./scripts/check.sh ]] || fail "scripts/check.sh not found"
./scripts/check.sh "${base_file}" > /dev/null \
    || fail "${base_file} is not a valid Indigo environment; fix it before creating an instance"

env_file=".env.${name}"
if [[ -e "${env_file}" && ${force} -ne 1 ]]; then
    fail "${env_file} already exists; pass --force to overwrite"
fi

base_ports=()
new_ports=()
for key in "${port_keys[@]}"; do
    value="$(base_value "${key}")"
    [[ -n "${value}" ]] || fail "${key} is not set in ${base_file}"
    [[ "${value}" =~ ^[0-9]+$ ]] || fail "${key} is not a number in ${base_file}: ${value}"
    base_ports+=("${value}")
    new_ports+=("$((value + offset))")
done

for index in "${!port_keys[@]}"; do
    port="${new_ports[${index}]}"
    ((port >= 1 && port <= 65535)) \
        || fail "${port_keys[${index}]} would be out of range: ${port}"
    for other in "${!new_ports[@]}"; do
        if [[ "${other}" -lt "${index}" && "${new_ports[${other}]}" -eq "${port}" ]]; then
            fail "${port_keys[${index}]} and ${port_keys[${other}]} both map to port ${port}; choose a different offset"
        fi
    done
done

busy=0
if command -v lsof > /dev/null 2>&1; then
    for index in "${!port_keys[@]}"; do
        port="${new_ports[${index}]}"
        if lsof -nP -iTCP:"${port}" -sTCP:LISTEN > /dev/null 2>&1; then
            echo "warning: ${port_keys[${index}]} port ${port} is already in use on this host" >&2
            busy=1
        fi
    done
fi

override_keys="COMPOSE_PROJECT_NAME|INDIGO_HOSTNAME|PINOKIO_DOMAIN|INDIGO_WORKSPACE_PATH|INDIGO_MODELS_PATH|INDIGO_LLAMA_SWAP_CONFIG_PATH"
for key in "${port_keys[@]}"; do
    override_keys="${override_keys}|${key}"
done

{
    printf '# Generated by scripts/new.sh from %s with port offset %+d\n' "${base_file}" "${offset}"
    printf '# Start it with: docker compose --env-file %s -p indigo-%s up --detach\n' "${env_file}" "${name}"
    grep -E '^[A-Za-z_][A-Za-z0-9_]*=' "${base_file}" \
        | grep -vE "^(${override_keys})=" || true
    printf 'COMPOSE_PROJECT_NAME=indigo-%s\n' "${name}"
    printf 'INDIGO_HOSTNAME=indigo-%s\n' "${name}"
    printf 'PINOKIO_DOMAIN=%s.pinokio.localhost\n' "${name}"
    printf 'INDIGO_WORKSPACE_PATH=./.indigo/%s/workspace\n' "${name}"
    printf 'INDIGO_MODELS_PATH=./.indigo/%s/models\n' "${name}"
    printf 'INDIGO_LLAMA_SWAP_CONFIG_PATH=./.indigo/%s/llama-swap\n' "${name}"
    for index in "${!port_keys[@]}"; do
        printf '%s=%s\n' "${port_keys[${index}]}" "${new_ports[${index}]}"
    done
} > "${env_file}"

./scripts/check.sh "${env_file}" > /dev/null \
    || fail "generated ${env_file} did not pass validation; remove it and retry"

echo "wrote ${env_file}"
for index in "${!port_keys[@]}"; do
    printf '  %-30s %5s -> %5s\n' "${port_keys[${index}]}" "${base_ports[${index}]}" "${new_ports[${index}]}"
done
printf '  %-34s %s\n' "INDIGO_WORKSPACE_PATH" "./.indigo/${name}/workspace"
printf '  %-34s %s\n' "INDIGO_MODELS_PATH" "./.indigo/${name}/models"
printf '  %-34s %s\n' "INDIGO_LLAMA_SWAP_CONFIG_PATH" "./.indigo/${name}/llama-swap"
echo
echo "  docker compose --env-file ${env_file} -p indigo-${name} up --detach"

if [[ ${busy} -ne 0 ]]; then
    echo
    echo "note: some ports are already in use; review the warnings above" >&2
fi
